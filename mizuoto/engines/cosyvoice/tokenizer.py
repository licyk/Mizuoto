class QwenTokenizer:
    def __init__(self, folder: Path, version: int) -> None:
        from tokenizers import AddedToken

        from mizuoto.text.tokenize.bpe import load_bpe

        self.bpe = load_bpe(folder)
        specials = ["<|endoftext|>", *(COSYVOICE3_SPECIALS if version == 3 else COSYVOICE2_SPECIALS)]
        self.bpe.tokenizer.add_special_tokens([AddedToken(t, special=True, normalized=False) for t in specials])

    def encode(self, text: str) -> list[int]:
        return self.bpe.encode(text)

    def token_to_id(self, token: str) -> int:
        return self.bpe.token_to_id(token)


def text_tokenizer(model_dir: Path, version: int) -> Any:
    """The tokenizer of a CosyVoice model folder (version 1, 2 or 3)."""
    if version == 1:
        from mizuoto.text.tokenize.whisper import WhisperTokenizer

        return WhisperTokenizer(num_languages=100)
    return QwenTokenizer(model_dir / "CosyVoice-BlankEN", version)
